import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import swaggerUi from 'swagger-ui-express';
import YAML from 'yaml';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import authRoutes from './routes/authRoutes.js';
import readingRoutes from './routes/readingRoutes.js';
import { GENRES } from './constants/genres.js';
import { notFound, handleError } from './middlewares/errors.js';
const currentDir = dirname(fileURLToPath(import.meta.url));
const spec = YAML.parse(readFileSync(join(currentDir, '..', 'openapi.yaml'), 'utf8'));
export const app = express();
app.disable('x-powered-by');
app.use(helmet({ contentSecurityPolicy: false }));
app.use(cors({ origin: (process.env.CORS_ORIGIN || 'http://localhost:5173').split(',').map(item => item.trim()) }));
app.use(express.json({ limit: '32kb' }));
app.get('/api/health', (req, res) => res.json({ status: 'ok' }));
app.get('/api/genres', (req, res) => res.json(GENRES));
app.use('/api/docs', swaggerUi.serve, swaggerUi.setup(spec));
app.get('/api/openapi.yaml', (req, res) => res.sendFile(join(currentDir, '..', 'openapi.yaml')));
app.use('/api/auth', authRoutes);
app.use('/api/readings', readingRoutes);
app.use(notFound);
app.use(handleError);
